import { describe, expect, test } from "bun:test";
import { readFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { unzipSync, strFromU8 } from "fflate";
import { renderToStaticMarkup } from "react-dom/server";
import { foxPalette, foxParts, foxClips, foxPose, type FoxClip } from "../assets/fox/model";
import { buildFox, foxAnimation, foxSvg, lottiePath } from "../scripts/build-fox";
import { foxAssets } from "@/content/fox";
import { LottieAnimation } from "@/components/animations/lottie-animation";

describe("original fox rig and exports", () => {
  test("the rig retains named editable layers and the existing character palette", () => {
    const css = readFileSync("src/app/globals.css", "utf8");
    for (const [name, value] of Object.entries(foxPalette)) expect(css).toContain(`--character-${name}: ${value}`);
    expect(new Set(foxParts.map(part => part.id)).size).toBe(foxParts.length);
    expect(foxParts.map(part => part.id)).toEqual(["tail", "far-hind-leg", "far-front-leg", "body", "near-hind-leg", "near-front-leg", "head"]);
    const layered = readFileSync("assets/fox/fox-layered.svg", "utf8");
    for (const part of foxParts) expect(layered).toContain(`inkscape:label="${part.id}"`);
    expect(layered).toBe(foxSvg("rest", true));
    for (const pose of ["rest", "notice", "follow", "settle"] as const) {
      const svg = readFileSync(`public/characters/fox/${pose}.svg`, "utf8");
      expect(svg).toBe(foxSvg(pose)); expect(svg).toContain('viewBox="0 0 192 160"');
      for (const bad of ["<image", "<script", "<filter", "http://uploads", "base64"]) expect(svg).not.toContain(bad);
      for (const part of foxParts) expect(svg).toContain(`id="${part.id}"`);
    }
    expect(foxPose("rest", "head")).toEqual({ rotation: 0, y: 0 });
  });
  test("compressed clips are self-contained, short, non-looping and match inspectable JSON", () => {
    for (const clip of Object.keys(foxClips) as FoxClip[]) {
      const archive = readFileSync(`public${foxAssets[clip].src}`);
      expect(archive.length).toBeLessThan(3000);
      const files = unzipSync(archive);
      expect(Object.keys(files).sort()).toEqual([`animations/${clip}.json`, "manifest.json"].sort());
      expect(JSON.parse(strFromU8(files["manifest.json"])).animations).toEqual([{ id: clip, loop: false, autoplay: false }]);
      const animation = JSON.parse(strFromU8(files[`animations/${clip}.json`]));
      expect(animation).toEqual(foxAnimation(clip));
      expect(animation).toEqual(JSON.parse(readFileSync(`public/animations/fox/${clip}.json`, "utf8")));
      expect(animation.op / animation.fr).toBe(foxAssets[clip].duration);
      expect(animation.assets).toEqual([]); expect(animation.layers).toHaveLength(7);
      expect(animation.markers.at(-1).cm).toBe("rest");
      for (const layer of animation.layers) for (const property of [layer.ks.r, layer.ks.p]) {
        if (property.a) expect(property.k.at(-1).s).toEqual(property.k[0].s);
      }
    }
  });
  test("vector conversion preserves closed cubic contours and generated bytes reproduce exactly", () => {
    expect(lottiePath("M0 0 L10 0 L10 10 Z").v).toHaveLength(3);
    for (const part of foxParts) for (const path of part.paths) {
      const shape = lottiePath(path.d);
      expect(shape.c).toBe(true); expect(shape.v.length).toBe(shape.i.length); expect(shape.v.length).toBe(shape.o.length);
      expect(shape.v.flat().every(Number.isFinite)).toBe(true);
    }
    const before = readFileSync("public/animations/fox/notice.lottie"); buildFox();
    expect(readFileSync("public/animations/fox/notice.lottie")).toEqual(before);
    expect(statSync("public/animations/runtime/dotlottie-player.wasm").size).toBeGreaterThan(100000);
    expect(createHash("sha256").update(readFileSync("public/animations/runtime/dotlottie-player.wasm")).digest("hex"))
      .toBe(createHash("sha256").update(readFileSync("node_modules/@lottiefiles/dotlottie-web/dist/dotlottie-player.wasm")).digest("hex"));
    expect(readFileSync("public/animations/runtime/LICENSE.txt", "utf8")).toContain("MIT");
    const manifest = JSON.parse(readFileSync("assets/fox/manifest.json", "utf8"));
    for (const file of manifest.files) expect(createHash("sha256").update(readFileSync(file.path)).digest("hex")).toBe(file.sha256);
  });
  test("server rendering provides a decorative static fallback before animation code loads", () => {
    const html = renderToStaticMarkup(<LottieAnimation src={foxAssets.notice.src} className="h-10 w-12" fallback={<span>Static fox</span>} />);
    expect(html).toContain("Static fox"); expect(html).toContain('aria-hidden="true"'); expect(html).not.toContain("<canvas");
  });
});
